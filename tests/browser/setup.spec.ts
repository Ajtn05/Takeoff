import { test, expect } from '@playwright/test';

test('Guide covers startup, keyboard and phone controls, connections and layout in desktop and fullscreen', async ({ page }) => {
  await page.goto('/'); await expect(page.locator('#connection-status')).toContainText('Keyboard');
  const guide = page.getByRole('button', { name: 'Guide', exact: true });
  await guide.click(); await expect(page.getByRole('dialog', { name: 'Guide', exact: true })).toBeVisible();
  await expect(page.getByRole('tabpanel', { name: 'Startup', exact: true })).toContainText('Your first flight');
  await page.getByRole('tab', { name: 'Controls', exact: true }).click();
  await expect(page.getByRole('tabpanel', { name: 'Controls', exact: true })).toContainText('Left stick up / down');
  await page.getByRole('tab', { name: 'Controls', exact: true }).press('ArrowRight');
  await expect(page.getByRole('tab', { name: 'Connection', exact: true })).toBeFocused();
  await expect(page.getByRole('tabpanel', { name: 'Connection', exact: true })).toContainText('Local Android USB');
  await page.getByRole('button', { name: 'Open pairing' }).click();
  await expect(page.locator('#guide-dialog')).not.toBeVisible(); await expect(page.locator('#pair-dialog')).toBeVisible();
  await page.getByRole('button', { name: 'Close pairing' }).click();
  await page.locator('#takeoff').click(); await expect(page.locator('#flight-status')).toHaveAttribute('data-mode', 'flying', { timeout: 10_000 });
  await guide.click(); await expect(page.locator('#flight-status')).toHaveAttribute('data-paused', 'true');
  const altitude = await page.locator('#altitude').innerText();
  await page.keyboard.press('w'); await page.keyboard.press('t');
  await expect(page.locator('#altitude')).toHaveText(altitude);
  await page.getByRole('tab', { name: 'Layout', exact: true }).click();
  await expect(page.getByRole('tabpanel', { name: 'Layout', exact: true })).toContainText('Shift-drag');
  await page.screenshot({ path: 'test-results/guide-desktop.png' });
  await page.keyboard.press('Escape'); await expect(page.locator('#guide-dialog')).not.toBeVisible(); await expect(guide).toBeFocused();
  await page.locator('#simulator-fullscreen').click(); await expect(guide).toBeVisible();
  await page.setViewportSize({ width: 320, height: 568 });
  await guide.click(); await page.getByRole('tab', { name: 'Startup', exact: true }).click();
  await expect(page.locator('#guide-startup')).toBeVisible();
  expect(await page.locator('#guide-dialog').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/guide-mobile.png' });
  await page.keyboard.press('Escape'); await expect(page.locator('#guide-dialog')).not.toBeVisible();
  await expect(page.locator('.simulator')).toHaveClass(/is-fullscreen/);
  await page.locator('#simulator-fullscreen').click(); await expect(guide).toBeVisible();
});

