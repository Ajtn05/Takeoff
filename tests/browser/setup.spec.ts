test('fixed observer can orbit, pan and zoom, keeps its viewpoint through other cameras, and resets', async ({ page }) => {
  await page.goto('/'); await expect(page.locator('#connection-status')).toContainText('Keyboard');
  const view = page.locator('#observer-view'), mode = page.locator('#observer-mode');
  const image = () => view.screenshot({ animations: 'disabled', style: '#fixed-view-hint, .view-heading { visibility: hidden; } .observer-view { outline: none !important; }' });
  await page.mouse.move(0, 0);
  const initial = await image(), rect = (await view.boundingBox())!;
  const drag = async (dx: number, dy: number) => {
    await page.mouse.move(rect.x + rect.width * .45, rect.y + rect.height * .4); await page.mouse.down();
    await page.mouse.move(rect.x + rect.width * .45 + dx, rect.y + rect.height * .4 + dy, { steps: 8 }); await page.mouse.up(); await page.mouse.move(0, 0);
  };
  await drag(90, 25); const orbited = await image(); expect(orbited.equals(initial)).toBe(false);
  await page.keyboard.down('Shift'); await drag(40, 0); await page.keyboard.up('Shift');
  const panned = await image(); expect(panned.equals(orbited)).toBe(false);
  await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height * .4); await page.mouse.wheel(0, -250); await page.mouse.move(0, 0);
  const zoomed = await image(); expect(zoomed.equals(panned)).toBe(false);
  await mode.selectOption('follow'); await expect(page.locator('#observer-reset')).toBeHidden();
  await mode.selectOption('overview'); await mode.selectOption('fixed'); await page.mouse.move(0, 0);
  expect((await image()).equals(zoomed)).toBe(true);
  await view.focus(); await page.keyboard.press('Alt+ArrowLeft'); const keyboardPan = await image(); expect(keyboardPan.equals(zoomed)).toBe(false);
  await page.keyboard.press('Alt+Equal'); expect((await image()).equals(keyboardPan)).toBe(false);
  await page.locator('#observer-reset').click(); await page.mouse.move(0, 0); expect((await image()).equals(initial)).toBe(true);
  await page.locator('#takeoff').click(); await expect(page.locator('#flight-status')).toHaveAttribute('data-mode', 'flying', { timeout: 10_000 });
  await view.focus(); await page.keyboard.down('ArrowRight');
  await expect.poll(async () => parseFloat(await page.locator('#speed').innerText())).toBeGreaterThan(0); await page.keyboard.up('ArrowRight');
});
